DROP SCHEMA IF EXISTS app CASCADE;
CREATE SCHEMA app AUTHORIZATION rbpo_owner;

CREATE TABLE app.users
(
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  VARCHAR(255) NOT NULL,
    email VARCHAR(255) UNIQUE
);

CREATE TABLE app.celestial_objects
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(255)     NOT NULL UNIQUE,
    type         VARCHAR(255)     NOT NULL,
    min_aperture DOUBLE PRECISION NOT NULL CHECK (min_aperture > 0)
);

CREATE TABLE app.telescopes
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255)     NOT NULL,
    aperture    DOUBLE PRECISION NOT NULL CHECK (aperture > 0),
    available   BOOLEAN          NOT NULL DEFAULT TRUE,
    maintenance BOOLEAN          NOT NULL DEFAULT FALSE
);

CREATE TABLE app.observation_sessions
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    celestial_object_id BIGINT       NOT NULL REFERENCES app.celestial_objects (id) ON DELETE CASCADE,
    telescope_id        BIGINT       NOT NULL REFERENCES app.telescopes (id) ON DELETE CASCADE,
    observer_id         BIGINT       NOT NULL REFERENCES app.users (id) ON DELETE CASCADE,
    start_time          TIMESTAMP,
    end_time            TIMESTAMP,
    status              VARCHAR(255) NOT NULL DEFAULT 'PLANNED'
        CHECK (status IN ('PLANNED', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED')),
    CHECK (start_time IS NULL OR end_time IS NULL OR end_time > start_time)
);

CREATE TABLE app.observation_records
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id  BIGINT    NOT NULL REFERENCES app.observation_sessions (id) ON DELETE CASCADE,
    record_time TIMESTAMP NOT NULL,
    description VARCHAR(1000),
    quality     INTEGER   NOT NULL CHECK (quality BETWEEN 1 AND 5)
);

GRANT USAGE ON SCHEMA app TO rbpo_service;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA app TO rbpo_service;
